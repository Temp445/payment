-- ==============================================================================
-- CENTRALIZED SUBSCRIPTION & LICENSING ENGINE MIGRATION
-- Supports Multi-Tenant 20+ Applications (Client-Only & Server-Backed)
-- ==============================================================================

-- 1. Currency Enum
DO $$ BEGIN
  CREATE TYPE public.pay_currency AS ENUM ('INR', 'USD', 'EUR', 'GBP', 'AED');
EXCEPTION
  WHEN duplicate_object THEN null;
END $$;

-- 2. Products Offers (Scoped to applications table)
CREATE TABLE IF NOT EXISTS public.products_offers (
  id uuid DEFAULT gen_random_uuid() NOT NULL PRIMARY KEY,
  application_id text NOT NULL REFERENCES public.applications(id) ON DELETE CASCADE,
  product_code text NOT NULL,          -- e.g. 'CRM_SAAS', 'ERP_PORTAL', 'DIALER_PRO'
  product_name text NOT NULL,
  available_from date NOT NULL DEFAULT CURRENT_DATE,
  product_is_active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz DEFAULT now(),
  UNIQUE(application_id, product_code)
);

-- 3. Subscription Offers (Tiers & Limits per Product)
CREATE TABLE IF NOT EXISTS public.subscription_offers (
  id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
  product_id uuid NOT NULL REFERENCES public.products_offers(id) ON DELETE CASCADE,
  tier text NOT NULL,                  -- 'Starter', 'Professional', 'Enterprise'
  tier_level integer NOT NULL DEFAULT 1,
  offer_price double precision NOT NULL DEFAULT 0,
  offer_currency public.pay_currency NOT NULL DEFAULT 'INR',
  offer_period integer NOT NULL DEFAULT 1,
  offer_period_type text NOT NULL DEFAULT 'month', -- 'day', 'month', 'year'
  user_limit integer NOT NULL DEFAULT 5,
  tier_limits jsonb DEFAULT '{"features": []}'::jsonb,
  offer_is_active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz DEFAULT now()
);

-- 4. User Subscriptions (Master Entitlement / License Table)
CREATE TABLE IF NOT EXISTS public.user_subscriptions (
  id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
  product_id uuid NOT NULL REFERENCES public.products_offers(id) ON DELETE CASCADE,
  offer_id bigint NOT NULL REFERENCES public.subscription_offers(id) ON DELETE CASCADE,
  offer_starts_on date NOT NULL DEFAULT CURRENT_DATE,
  offer_ends_on date NOT NULL DEFAULT (CURRENT_DATE + INTERVAL '30 days'),
  offer_is_active boolean NOT NULL DEFAULT true,
  organization_id text NOT NULL,
  user_id text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz DEFAULT now(),
  is_trial_period boolean DEFAULT false,
  UNIQUE(organization_id, product_id)  -- Ensures 1 active subscription per org per product
);

-- 5. Payment Transactions (Subscription Payments Ledger)
CREATE TABLE IF NOT EXISTS public.payment_transactions (
  id uuid DEFAULT gen_random_uuid() NOT NULL PRIMARY KEY,
  gateway_payment_id text,             -- Gateway payment ID (e.g. Cashfree cf_payment_id)
  gateway_order_id text,               -- Gateway order ID (e.g. Cashfree cf_order_id)
  gateway_signature text,              -- Gateway verification signature or webhook hash
  gateway_name text DEFAULT 'CASHFREE', -- 'CASHFREE', 'STRIPE', 'RAZORPAY'
  amount numeric NOT NULL,
  currency text NOT NULL DEFAULT 'INR',
  status text NOT NULL DEFAULT 'PAID',
  receipt_number text NOT NULL,
  product_id uuid NOT NULL REFERENCES public.products_offers(id) ON DELETE CASCADE,
  offer_id bigint NOT NULL REFERENCES public.subscription_offers(id) ON DELETE CASCADE,
  offer_period integer NOT NULL DEFAULT 1,
  offer_period_type text NOT NULL DEFAULT 'month',
  organization_id text NOT NULL,
  user_id text,
  created_at timestamptz DEFAULT now(),
  updated_at timestamptz DEFAULT now()
);

-- 6. Trigger: Automatic Subscription Activation & Date Calculation
CREATE OR REPLACE FUNCTION public.handle_subscription_activation()
RETURNS trigger AS $$
DECLARE
  v_period_interval interval;
  v_new_start date := CURRENT_DATE;
  v_new_end date;
  v_existing_end date;
BEGIN
  -- Only process successful payments
  IF NEW.status NOT IN ('PAID', 'captured', 'SUCCESS') THEN
    RETURN NEW;
  END IF;

  -- Determine duration interval
  IF NEW.offer_period_type = 'year' THEN
    v_period_interval := (NEW.offer_period || ' years')::interval;
  ELSIF NEW.offer_period_type = 'day' THEN
    v_period_interval := (NEW.offer_period || ' days')::interval;
  ELSE
    v_period_interval := (NEW.offer_period || ' months')::interval;
  END IF;

  -- Check if organization already has an unexpired subscription for this product
  SELECT offer_ends_on INTO v_existing_end
  FROM public.user_subscriptions
  WHERE organization_id = NEW.organization_id 
    AND product_id = NEW.product_id 
    AND offer_ends_on >= CURRENT_DATE;

  -- If already active, extend from existing expiry date; otherwise start today
  IF v_existing_end IS NOT NULL THEN
    v_new_start := CURRENT_DATE;
    v_new_end := (v_existing_end + v_period_interval)::date;
  ELSE
    v_new_start := CURRENT_DATE;
    v_new_end := (CURRENT_DATE + v_period_interval)::date;
  END IF;

  -- Upsert into user_subscriptions
  INSERT INTO public.user_subscriptions (
    product_id,
    offer_id,
    offer_starts_on,
    offer_ends_on,
    offer_is_active,
    organization_id,
    user_id,
    updated_at
  ) VALUES (
    NEW.product_id,
    NEW.offer_id,
    v_new_start,
    v_new_end,
    true,
    NEW.organization_id,
    COALESCE(NEW.user_id, gen_random_uuid()::text),
    now()
  )
  ON CONFLICT (organization_id, product_id)
  DO UPDATE SET
    offer_id = EXCLUDED.offer_id,
    offer_starts_on = EXCLUDED.offer_starts_on,
    offer_ends_on = EXCLUDED.offer_ends_on,
    offer_is_active = true,
    updated_at = now();

  RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

DROP TRIGGER IF EXISTS trigger_activate_subscription ON public.payment_transactions;
CREATE TRIGGER trigger_activate_subscription
AFTER INSERT ON public.payment_transactions
FOR EACH ROW EXECUTE FUNCTION public.handle_subscription_activation();

